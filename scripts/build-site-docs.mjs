import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectSnapshot } from './publication.mjs';

// Deliberately narrower than the source export: no release operations or decision history.
export const readerPaths = [
  'SPEC.md', 'docs/vision.md', 'docs/cogposix.md', 'docs/architecture.md',
  'docs/distributed-intelligence.md', 'docs/deployment-examples.md',
  'docs/models-and-capabilities.md', 'docs/operating-system.md', 'docs/security.md',
  'docs/adaptive-optimization.md', 'docs/roadmap.md', 'docs/development.md',
  'docs/protocol.md', 'docs/onnx-worker.md', 'docs/shared-memory.md',
  'docs/implementation-r1.md', 'docs/r2-review.md', 'docs/sources.md',
  'CONTRIBUTING.md', 'SECURITY.md', 'LICENSE-SCOPE.md', 'TERMS.md', 'TRADEMARKS.md',
  'assets/BRAND-NOTICE.md', 'site/THIRD-PARTY.md', 'LICENSE',
  'LICENSES/CC-BY-4.0.txt', 'site/vendor/MARKED-LICENSE.txt', 'site/vendor/DOMPURIFY-LICENSE.txt',
];

export function documentBundle(root) {
  const snapshot = collectSnapshot(root);
  return documentBundleFromSnapshot(snapshot);
}

export function documentBundleFromSnapshot(snapshot) {
  const documents = {};
  for (const name of readerPaths) {
    const file = snapshot.files.find(file => file.path === name);
    if (!file) throw new Error(`Reader document is not approved: ${name}`);
    const content = file.data.toString('utf8');
    documents[name] = {
      title: name.endsWith('.md') ? content.match(/^# (.+)$/m)?.[1] ?? name : name,
      content, license: file.license,
    };
  }
  const payload = { documents, files: snapshot.files.map(file => file.path) };
  return '// Generated by scripts/build-site-docs.mjs; source licenses and notices are preserved.\n' +
    `window.ECOS_DOCUMENTS = ${JSON.stringify(payload).replaceAll('<', '\\u003c')};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const target = path.join(root, 'site/documents.js');
  const generated = documentBundle(root);
  if (process.argv[2] === '--check') {
    if (fs.readFileSync(target, 'utf8') !== generated) throw new Error('Reader bundle is stale; run node scripts/build-site-docs.mjs');
    console.log('Public document reader bundle is current.');
  } else if (process.argv.length === 2) {
    fs.writeFileSync(target, generated);
    console.log(`Bundled ${readerPaths.length} approved documents; no deployment notes included.`);
  } else throw new Error('Usage: node scripts/build-site-docs.mjs [--check]');
}
